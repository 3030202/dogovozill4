"""Term of Agreement and Termination Clauses (ГК РФ) — with LegalStance support."""

from __future__ import annotations
from typing import List, Dict, Any
from core.models.base import BaseContract
from core.models.nda import NDAContract
from core.models.stance import LegalStance


def build_term_termination_clauses(contract: BaseContract) -> List[Dict[str, str]]:
    """Generate Section: Срок действия и порядок расторжения Договора."""
    clauses = []
    stance = contract.legal_stance

    if isinstance(contract, NDAContract):
        years = contract.nda_terms.confidentiality_years
        clauses.append({
            "num": "8.1",
            "text": (
                f"Настоящее Соглашение вступает в силу с даты его подписания обеими Сторонами и действует в течение {years} ({years}) лет."
            )
        })
        clauses.append({
            "num": "8.2",
            "text": (
                f"Обязательства по сохранению конфиденциальности остаются в силе в течение {years} лет после прекращения действия Соглашения."
            )
        })
        return clauses

    valid_until_str = contract.metadata.valid_until or "до полного исполнения Сторонами всех принятых на себя обязательств"
    clauses.append({
        "num": "8.1",
        "text": (
            f"Настоящий Договор вступает в силу с даты его подписания уполномоченными представителями обеих Сторон "
            f"и действует {valid_until_str}."
        )
    })
    clauses.append({
        "num": "8.2",
        "text": (
            "Договор может быть изменен или расторгнут по взаимному соглашению Сторон, оформленному в виде "
            "дополнительного соглашения, подписанного обеими Сторонами."
        )
    })

    # --- Одностороннее расторжение — зависит от правовой позиции ---
    if stance == LegalStance.PRO_BUYER:
        # Заказчик может расторгнуть немедленно; Исполнитель должен уведомить за 60 дней
        clauses.append({
            "num": "8.3",
            "text": (
                "Заказчик вправе в одностороннем внесудебном порядке отказаться от исполнения Договора немедленно, "
                "письменно уведомив Исполнителя, при условии оплаты фактически понесенных расходов. "
                "Исполнитель вправе расторгнуть Договор в одностороннем порядке, письменно уведомив Заказчика "
                "не менее чем за 60 (шестьдесят) календарных дней до предполагаемой даты расторжения."
            )
        })
    elif stance == LegalStance.PRO_VENDOR:
        # Исполнитель может расторгнуть немедленно; Заказчик должен уведомить за 60 дней
        clauses.append({
            "num": "8.3",
            "text": (
                "Исполнитель вправе в одностороннем внесудебном порядке отказаться от исполнения Договора немедленно, "
                "письменно уведомив Заказчика, при условии завершения расчетов за выполненные работы / оказанные услуги. "
                "Заказчик вправе расторгнуть Договор в одностороннем порядке, письменно уведомив Исполнителя "
                "не менее чем за 60 (шестьдесят) календарных дней до предполагаемой даты расторжения."
            )
        })
    else:  # BALANCED
        clauses.append({
            "num": "8.3",
            "text": (
                "Любая из Сторон вправе в одностороннем внесудебном порядке отказаться от исполнения Договора, "
                "письменно уведомив другую Сторону не менее чем за 30 (тридцать) календарных дней до предполагаемой "
                "даты расторжения, при условии проведения полных взаиморасчетов за фактически поставленный Товар / "
                "оказанные услуги / выполненные работы."
            )
        })

    if contract.additional_terms:
        clauses.append({
            "num": "8.4",
            "text": f"Особые условия: {contract.additional_terms}"
        })

    return clauses
