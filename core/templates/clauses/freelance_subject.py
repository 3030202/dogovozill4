"""Subject and Special Clauses for Freelance / Self-employed (ГПХ) Contract."""

from __future__ import annotations
from typing import List, Dict, Any
from core.models.freelance import FreelanceContract


def build_freelance_subject_clauses(contract: FreelanceContract) -> List[Dict[str, str]]:
    """Section 1 — Предмет договора ГПХ с самозанятым / фрилансером."""
    terms = contract.freelance_terms
    tasks = contract.tasks

    task_list = "; ".join(f"{t.name}" for t in tasks) or "по заданиям Заказчика"

    clauses = [
        {
            "num": "1.1",
            "text": (
                f"Исполнитель обязуется по заданию Заказчика выполнить следующие работы (оказать услуги): {task_list} "
                f"(далее — «Результат»), а Заказчик обязуется принять и оплатить Результат в порядке и сроки, "
                f"предусмотренные настоящим Договором."
            )
        },
        {
            "num": "1.2",
            "text": (
                "Исполнитель выполняет работы лично, своими силами и средствами. "
                "Привлечение третьих лиц (соисполнителей) допускается исключительно с предварительного "
                "письменного согласия Заказчика."
            )
        },
    ]

    # Пункт о самозанятом и чеке НПД
    if terms.is_self_employed:
        clauses.append({
            "num": "1.3",
            "text": (
                "Исполнитель является плательщиком налога на профессиональный доход (НПД) в соответствии "
                "с Федеральным законом от 27.11.2018 № 422-ФЗ «О проведении эксперимента по установлению "
                "специального налогового режима «Налог на профессиональный доход»»."
                + (
                    " Исполнитель обязан сформировать и передать Заказчику чек из приложения «Мой налог» "
                    "не позднее следующего рабочего дня после получения вознаграждения."
                    if terms.check_receipt_required else ""
                )
                + " Заказчик не является налоговым агентом Исполнителя и не удерживает НДФЛ и страховые взносы."
            )
        })

    # Передача прав на результат
    if terms.ip_rights_transfer:
        clauses.append({
            "num": "1.4",
            "text": (
                "Исключительное право на Результат (объект интеллектуальной собственности, созданный в ходе "
                "исполнения Договора) переходит к Заказчику в полном объеме с момента подписания Сторонами "
                "Акта приемки-сдачи работ / оказанных услуг и полной оплаты вознаграждения."
            )
        })

    # Антиподмена трудовых отношений
    if terms.no_employment_relations:
        clauses.append({
            "num": "1.5",
            "text": (
                "Настоящий Договор не является трудовым, не порождает отношений работника и работодателя, "
                "не предусматривает предоставления Исполнителю социальных гарантий, предусмотренных трудовым "
                "законодательством (ст. 15 ТК РФ). Исполнитель самостоятельно организует свою деятельность "
                "и не обязан соблюдать внутренний трудовой распорядок Заказчика."
            )
        })

    return clauses
